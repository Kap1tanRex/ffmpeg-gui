"""Тексты контекстных подсказок ⓘ рядом с параметрами (раздел 32).

Подсказка отвечает на три вопроса подряд, и в таком же порядке показывается:

1. **Зачем** параметр нужен — одна строка, без терминов, если можно.
2. **Какие значения** он принимает и что каждое из них означает.
3. **Что будет с файлом** — то, ради чего пользователь сюда и смотрит:
   станет ли он больше, дольше ли будет кодироваться, что увидит глаз.

Плюс необязательное предупреждение о том, чего параметр НЕ делает или где
он подводит. GUI запрашивает запись по ключу; отсутствующий ключ ошибкой не
считается — виджет подсказки просто не появляется.
"""

from __future__ import annotations

from dataclasses import dataclass

#: Роли строк подсказки. Совпадают с именами стилей в ``gui.widgets.hint``.
TITLE, BODY, VALUES, EFFECT, WARNING = "title", "body", "values", "effect", "warning"


@dataclass
class HelpEntry:
    brief: str
    detailed: str = ""
    values: str = ""
    effect: str = ""
    warning: str = ""

    def sections(self) -> list[tuple[str, str]]:
        """Строки подсказки как (роль, текст) — для оформления по ролям."""
        parts = [(TITLE, self.brief)]
        for role, text in (
            (BODY, self.detailed),
            (VALUES, self.values),
            (EFFECT, self.effect),
            (WARNING, self.warning),
        ):
            if text:
                parts.append((role, text))
        return parts

    def text(self) -> str:
        """Тот же текст сплошняком — для мест, где оформления нет."""
        lines = [self.brief]
        for prefix, text in (
            ("", self.detailed),
            ("Значения: ", self.values),
            ("На результат: ", self.effect),
            ("⚠ ", self.warning),
        ):
            if text:
                lines.append(prefix + text)
        return "\n\n".join(lines)


# ── шкала качества CRF ───────────────────────────────────────────────────────
# Верхняя граница диапазона, подпись, уровень. Шкала записана для 0–51
# (H.264/HEVC); кодеки с диапазоном 0–63 приводятся к ней пересчётом.
#
# Направление здесь именно такое: CRF — это «на сколько разрешено ухудшить».
# Ноль означает «не ухудшать вовсе», поэтому чем БОЛЬШЕ число, тем сильнее
# сжатие и тем ближе результат к шакальности.
_CRF_SCALE: tuple[tuple[float, str, str], ...] = (
    (0, "без потерь", "ok"),
    (17, "избыточное — глаз не увидит разницы, а файл огромный", "info"),
    (20, "отличное — от оригинала не отличить", "ok"),
    (27, "хорошее — годится для большинства задач", "ok"),
    (32, "среднее — артефакты заметны на движении", "warn"),
    (40, "низкое — заметная блочность и мыло", "warn"),
    (63, "шакальность", "error"),
)

#: Кодеки со шкалой 0–63 вместо 0–51.
_WIDE_SCALE_CODECS = frozenset({"av1", "vp9", "vp8"})


def crf_range(codec: str | None) -> tuple[float, float]:
    """Границы шкалы CRF для кодека."""
    if codec and codec.lower() in _WIDE_SCALE_CODECS:
        return 0.0, 63.0
    return 0.0, 51.0


def crf_quality(crf: float | None, codec: str | None = None) -> tuple[str, str]:
    """Подпись качества и уровень (``ok``/``info``/``warn``/``error``).

    Пользователю ни о чём не говорит само число: 23 — это много или мало,
    видно только по результату. Подпись отвечает на этот вопрос сразу.
    """
    if crf is None:
        return "", "muted"
    _low, high = crf_range(codec)
    # Приводим к шкале 0–51, на которой записаны пороги.
    normalized = float(crf) * 51.0 / high
    for bound, label, severity in _CRF_SCALE:
        if normalized <= bound:
            return label, severity
    return _CRF_SCALE[-1][1], _CRF_SCALE[-1][2]


class HelpRegistry:
    """Реестр подсказок; заполняется базовыми записями по умолчанию."""

    def __init__(self) -> None:
        self._entries: dict[str, HelpEntry] = {}
        self._register_defaults()

    def register(self, key: str, entry: HelpEntry) -> None:
        self._entries[key] = entry

    def get(self, key: str) -> HelpEntry | None:
        return self._entries.get(key)

    def text_for(self, key: str, default: str = "") -> str:
        entry = self.get(key)
        return entry.text() if entry else default

    def encoder_hint(self, encoder: str) -> str:
        """Раздел 32: контекстная подсказка для конкретного энкодера."""
        if encoder.endswith("_nvenc"):
            return (
                "NVIDIA NVENC — кодирует отдельный блок видеокарты. В 5–15 раз "
                "быстрее процессора, но при одном и том же размере файла картинка "
                "заметно грубее, чем у libx264/libx265."
            )
        if encoder.endswith("_qsv"):
            return (
                "Intel Quick Sync — блок кодирования встроенной графики Intel. "
                "Быстро и почти не нагружает процессор; качество между NVENC и libx264."
            )
        if encoder.endswith("_amf"):
            return (
                "AMD AMF — аппаратное кодирование на видеокарте AMD. Быстро, "
                "качество на том же размере файла ниже программных энкодеров."
            )
        if encoder.endswith("_vaapi"):
            return "VAAPI — аппаратное ускорение в Linux (Intel и AMD)."
        if encoder.startswith("libx264"):
            return (
                "libx264 — программный H.264. Лучшее соотношение качества, скорости "
                "и совместимости: такой файл откроется где угодно."
            )
        if encoder.startswith("libx265"):
            return (
                "libx265 — программный HEVC. При том же качестве файл примерно на "
                "треть меньше, чем H.264, но кодирует в несколько раз дольше, и "
                "старые устройства такое видео не откроют."
            )
        if encoder.startswith("libsvtav1") or encoder.startswith("libaom"):
            return (
                "AV1 — самый экономный из массовых кодеков, но и самый медленный. "
                "Поддержка на устройствах пока неполная."
            )
        return ""

